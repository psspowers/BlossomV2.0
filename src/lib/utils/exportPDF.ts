interface PDFExportOptions {
  includeCharts?: boolean;
  patientName?: string;
  dob?: string;
  sex?: string;
  hn?: string;
}

const COLORS = {
  cream: [250, 244, 237] as [number, number, number],
  pink: [232, 181, 181] as [number, number, number],
  sage: [107, 142, 35] as [number, number, number],
  darkGray: [60, 60, 60] as [number, number, number],
  lightGray: [150, 150, 150] as [number, number, number],
  black: [0, 0, 0] as [number, number, number],
};

const addWatermark = (doc: jsPDF, pageNumber: number, totalPages: number) => {
  doc.setFontSize(8);
  doc.setTextColor(...COLORS.lightGray);
  doc.text(`Page ${pageNumber} of ${totalPages}`, 105, 287, { align: 'center' });
  doc.text('Generated by Blossom PCOS Tracker', 105, 292, { align: 'center' });
};

const addPageBackground = (doc: jsPDF) => {
  doc.setFillColor(...COLORS.cream);
  doc.rect(0, 0, 210, 297, 'F');
};

const addHeader = (doc: jsPDF, title: string, yPosition: number = 20) => {
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...COLORS.sage);
  doc.text(title, 105, yPosition, { align: 'center' });

  doc.setDrawColor(...COLORS.pink);
  doc.setLineWidth(0.5);
  doc.line(20, yPosition + 3, 190, yPosition + 3);
};

const addSectionHeader = (doc: jsPDF, title: string, yPosition: number) => {
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...COLORS.sage);
  doc.text(title, 20, yPosition);

  return yPosition + 7;
};

const addText = (doc: jsPDF, text: string, x: number, y: number, options?: {
  fontSize?: number;
  color?: [number, number, number];
  bold?: boolean;
  align?: 'left' | 'center' | 'right';
}) => {
  doc.setFontSize(options?.fontSize || 10);
  doc.setFont('helvetica', options?.bold ? 'bold' : 'normal');
  doc.setTextColor(...(options?.color || COLORS.darkGray));
  doc.text(text, x, y, { align: options?.align || 'left' });
};

const addBlankField = (doc: jsPDF, label: string, x: number, y: number, width: number = 60) => {
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...COLORS.darkGray);
  doc.text(label, x, y);

  doc.setDrawColor(...COLORS.lightGray);
  doc.setLineWidth(0.3);
  const labelWidth = doc.getTextWidth(label);
  doc.line(x + labelWidth + 2, y + 0.5, x + labelWidth + width, y + 0.5);
};

